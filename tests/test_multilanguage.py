import difflib
import hashlib
import unittest
from unittest.mock import patch

from parsimony.analysis import generated, implementation, measure, parse_patch
from parsimony.benchmark import ANALYZER_VERSION, analyze_submission, leaderboard
from parsimony.languages import track
from tests.test_languages import HAS_GO, HAS_LANGUAGES


def diff(before, after, path):
    return ''.join(difflib.unified_diff(before.splitlines(keepends=True), after.splitlines(keepends=True),
                                       fromfile='a/' + path if before else '/dev/null', tofile='b/' + path))


class LanguageScopeTests(unittest.TestCase):
    def test_language_scope_and_exclusions(self):
        for lang, paths in {'javascript': ['src/a.js', 'index.mjs', 'ui.jsx', 'src/a.ts', 'ui.tsx'],
                            'typescript': ['src/a.ts', 'ui.tsx', 'src/a.js'],
                            'go': ['main.go', 'pkg/a.go']}.items():
            for path in paths:
                self.assertTrue(implementation(path, lang), (path, lang))
                self.assertFalse(implementation(path))
        for path in ['src/a.test.ts', 'src/a.spec.tsx', '__tests__/a.ts', 'types/a.d.ts',
                     'node_modules/x/a.ts', 'generated/a.ts', 'src/api.generated.ts',
                     'src/schema.generated.js', 'docs/a.ts', 'tests/a.ts']:
            self.assertFalse(implementation(path, 'typescript'), path)
        for path in ['main_test.go', 'x.pb.go', 'x_generated.go', 'testdata/main.go']:
            self.assertFalse(implementation(path, 'go'), path)
        with self.assertRaises(ValueError):
            implementation('src/x.rs', 'rust')

    def test_generated_headers(self):
        self.assertTrue(generated('// Code generated by protoc. DO NOT EDIT.\npackage x\n', 'go'))
        self.assertTrue(generated('/* Auto-generated file */\nconst x = 1;\n', 'javascript'))
        self.assertTrue(generated('// @generated\nconst x = 1;\n', 'typescript'))
        self.assertFalse(generated('const text = "generated by a user";', 'javascript'))

    def test_unsupported_diff_not_silently_dropped(self):
        for lang, path in [('javascript', 'src/a.js'), ('typescript', 'src/a.ts'), ('go', 'main.go')]:
            with self.assertRaises(ValueError):
                parse_patch(f'diff --git a/{path} b/{path}\nold mode 100644\nnew mode 100755\n', lang)

    def test_mixed_dataset_rejected_before_measurement(self):
        with self.assertRaisesRegex(ValueError, 'one supported language'):
            list(analyze_submission({}, None, [dict(instance_id='a', language='python'),
                                               dict(instance_id='b', language='go')]))
        with self.assertRaisesRegex(ValueError, 'mixed measurement tracks'):
            leaderboard([{'measurement_track': None}, {'measurement_track': {'language': 'go'}}])


@unittest.skipUnless(HAS_GO, 'optional Go grammar dependencies not installed')
class GoV2MeasurementTests(unittest.TestCase):
    def test_eof_only_change_has_zero_churn(self):
        before = 'package p\nfunc f() {\n println("hello")\n}'
        patch_text = ('--- a/main.go\n+++ b/main.go\n@@ -1,4 +1,4 @@\n'
                      ' package p\n func f() {\n  println("hello")\n-}\n'
                      '\\ No newline at end of file\n+}\n')
        m = measure(patch_text, lambda _: before, language='go')
        for key in ('churn', 'token_churn', 'structural_churn', 'files_changed',
                    'ast_delta', 'complexity_delta'):
            self.assertEqual(m[key], 0, key)
        self.assertEqual(m['measurement_track'], track('go'))

    def test_grouped_eof_and_new_expression_keep_original_provenance_hashes(self):
        source = 'package p\nvar (\n ptr = new("sample")\n)'
        patch_text = diff('', source + '\n', 'main.go') + '\\ No newline at end of file\n'
        m = measure(patch_text, lambda _: '', language='go')
        with_newline = measure(diff('', source + '\n', 'main.go'), lambda _: '', language='go')
        self.assertEqual(m, with_newline)
        submission = dict(agent='model', predictions={'task': patch_text}, resolved={'task'},
                          evaluated={'task'}, result_details={},
                          provenance={'prediction_url': 'https://example.org/'})
        reference = patch_text + '\n'
        dataset = [dict(instance_id='task', repo='org/repo', base_commit='abc',
                        patch=reference, language='go')]
        with patch('parsimony.benchmark.base_source', return_value=lambda _: ''):
            record, = analyze_submission(submission, None, dataset)
        self.assertEqual(record['analysis_status'], 'ok')
        self.assertEqual(record['analyzer_version'], '0.8.0-beta')
        self.assertEqual(ANALYZER_VERSION, record['analyzer_version'])
        self.assertEqual(record['provenance']['patch_sha256'], hashlib.sha256(patch_text.encode()).hexdigest())
        self.assertEqual(record['provenance']['reference_patch_sha256'],
                         hashlib.sha256(reference.encode()).hexdigest())
        self.assertEqual(record['measurement_track'], track('go'))
        old = {'language': 'go', 'unit_version': 'tree-sitter-units-v1',
               'versions': {'tree-sitter': '0.26.0', 'tree-sitter-go': '0.25.0'}}
        with self.assertRaisesRegex(ValueError, 'mixed measurement tracks'):
            leaderboard([{'measurement_track': old}, {'measurement_track': track('go')}])


@unittest.skipUnless(HAS_LANGUAGES, 'optional grammar dependencies not installed')
class LanguageMeasurementTests(unittest.TestCase):
    def test_added_root_files_are_measured(self):
        for language, path, text in [('go', 'main.go', 'package main\nfunc main() {}\n'),
                                     ('javascript', 'index.js', 'const value = 1;\n'),
                                     ('typescript', 'index.ts', 'const value: number = 1;\n')]:
            m = measure(diff('', text, path), lambda _: '', language=language)
            self.assertGreater(m['units_added'], 0)
            self.assertEqual(m['units_deleted'], 0)
            self.assertEqual(m['files_changed'], 1)
            self.assertEqual(m['measurement_track']['language'], language)

    def test_formatting_value_changes_and_invalid_syntax(self):
        for language, path, before, formatted, changed in [
            ('javascript', 'src/a.js', 'const a=1;\n', '// comment\nconst a = 1;\n', 'const b=2;\n'),
            ('typescript', 'src/a.ts', 'const a:number=1;\n', '// c\nconst a: number = 1;\n', 'const b:number=2;\n'),
            ('go', 'a.go', 'package p\nvar a=1\n', 'package p\n// c\nvar a = 1\n', 'package p\nvar b=2\n')]:
            for after, changes in [(formatted, False), (changed, True)]:
                m = measure(diff(before, after, path), lambda _: before, language=language)
                self.assertEqual(m['churn'] > 0, changes)
                self.assertEqual(m['files_changed'], int(changes))
                self.assertEqual(m['net_units'], 0)
                self.assertEqual(m['structural_churn'], 0)
            with self.assertRaisesRegex(ValueError, 'invalid or recovered'):
                measure(diff(before, 'function {\n', path), lambda _: before, language=language)
            with self.assertRaisesRegex(ValueError, 'full-file'):
                measure(diff(before, changed, path), language=language)

    def test_generated_header_cannot_hide_changes(self):
        before = 'const a = 1;\n'
        after = '// Code generated by agent. DO NOT EDIT.\nconst a = 2;\n'
        m = measure(diff(before, after, 'src/a.js'), lambda _: before, language='javascript')
        self.assertGreater(m['churn'], 0)

    def test_failed_attempt_is_measured_and_track_recorded(self):
        source = 'package p\nvar x = 1\n'
        patch_text = diff(source, 'package p\nvar x = 2\n', 'main.go')
        submission = dict(agent='model', predictions={'task': patch_text}, resolved=set(), evaluated={'task'},
                          result_details={'unresolved': ['task']}, provenance={'prediction_url': 'https://example.org/'})
        dataset = [dict(instance_id='task', repo='org/repo', base_commit='abc', patch='', language='go')]
        with patch('parsimony.benchmark.base_source', return_value=lambda _: source):
            r, = analyze_submission(submission, None, dataset, include_failed=True)
        self.assertEqual(r['analysis_status'], 'ok')
        self.assertFalse(r['resolved'])
        self.assertGreater(r['metrics']['churn'], 0)
        self.assertEqual(r['measurement_track'], r['metrics']['measurement_track'])
