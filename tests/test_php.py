import difflib
import importlib.util
import unittest
from importlib import metadata
from unittest.mock import patch

from parsimony import languages
from parsimony.analysis import generated, implementation, measure, parse_patch, token_diff
from parsimony.languages import extension_language, parse, structure, token_lines, track, unit_lines


HAS_PHP = all(importlib.util.find_spec(name) for name in ('tree_sitter', 'tree_sitter_php'))


def diff(before, after, path='src/calc.php'):
    return ''.join(difflib.unified_diff(before.splitlines(keepends=True), after.splitlines(keepends=True),
                                       fromfile='a/' + path if before else '/dev/null', tofile='b/' + path))


class PHPScopeTests(unittest.TestCase):
    def test_extensions_and_scope(self):
        self.assertIn('php', languages.SUPPORTED)
        for path in ('index.php', 'src/Calc.php', 'templates/page.phtml', 'src/CALC.PHP', 'src/Latest.php', 'app/Contest.php'):
            self.assertEqual(extension_language(path), 'php')
            self.assertTrue(implementation(path, 'php'))
            self.assertFalse(implementation(path))
        self.assertIsNone(extension_language('src/calc.inc'))
        for path in ('tests/Calc.php', 'test/Calc.php', 'src/CalcTest.php', 'Test.php',
                     'src/test_calc.php', 'src/calc.test.php', 'vendor/lib/Calc.php', 'vendored/Calc.php',
                     'third_party/Calc.php', 'docs/Calc.php', 'generated/Calc.php', 'src/calc.generated.php',
                     'migrations/Calc.php', 'src/calc.inc'):
            self.assertFalse(implementation(path, 'php'), path)

    def test_generated_headers(self):
        for header in ('// Code generated by tool. DO NOT EDIT.', '/* Auto-generated file */',
                       '/**\n * @generated\n */', '# Generated by tool', '// This file is generated by tool'):
            for separator in ('\n', ' '):
                self.assertTrue(generated('<?php' + separator + header + '\n$x = 1;\n', 'php'), header)
        self.assertFalse(generated('<?php\n$text = "generated by a user";\n', 'php'))

    def test_metadata_pin_and_install_guidance(self):
        with patch.object(languages.metadata, 'version', side_effect=languages._PHP_PINS.get), \
                patch.object(languages.metadata, 'distribution') as distribution:
            self.assertEqual(track('php'), {'language': 'php', 'unit_version': 'tree-sitter-php-units-v1',
                                           'versions': {'tree-sitter': '0.26.0', 'tree-sitter-php': '0.25.1'}})
            distribution.assert_not_called()
        with patch.object(languages.metadata, 'version', side_effect=metadata.PackageNotFoundError('tree-sitter-php')):
            with self.assertRaisesRegex(ValueError, 'pip install.*tree-sitter-php==0.25.1'):
                track('php')
        for name in languages._PHP_PINS:
            versions = {**languages._PHP_PINS, name: '0.0.0'}
            with patch.object(languages.metadata, 'version', side_effect=versions.get):
                with self.assertRaisesRegex(ValueError, 'requires exact versions'):
                    track('php')
                with self.assertRaisesRegex(ValueError, 'requires exact versions'):
                    parse('<?php $x = 1;', 'x.php')

    def test_metadata_only_diff_rejected(self):
        with self.assertRaisesRegex(ValueError, 'mode-only diff unsupported'):
            parse_patch('diff --git a/src/a.php b/src/a.php\nold mode 100644\nnew mode 100755\n', 'php')


@unittest.skipUnless(HAS_PHP, 'install parsimony-benchmark[languages] for PHP grammar tests')
class PHPMeasurementTests(unittest.TestCase):
    def measurement(self, before, after, path='src/calc.php'):
        return measure(diff(before, after, path), lambda _: before, language='php')

    def labels(self, source, keep_values=True):
        return [label for row in unit_lines(parse(source, 'x.php'), keep_values) for label in row]

    def test_worked_example(self):
        before = ('<?php\nfunction total($items) {\n    $result = 0;\n    foreach ($items as $item) {\n'
                  '        $result = $result + $item;\n    }\n    return $result;\n}\n')
        after = '<?php\nfunction total($items) {\n    return array_sum($items);\n}\n'
        m = self.measurement(before, after)
        self.assertLess(m['net_units'], 0)
        self.assertGreater(m['units_deleted'], m['units_added'])
        self.assertEqual(m['complexity_delta'], -1)
        self.assertEqual(m['measurement_track'], track('php'))

    def test_comments_whitespace_and_formatting(self):
        before = '<?php\nfunction f($x){$s="hello";return $x+1;}\n'
        for after in ('<?php\n// note\n# note\n/* note */\nfunction f($x){$s="hello";return $x+1;}\n',
                      '<?php\n\nfunction f($x) {\n    $s = "hello";\n    return $x + 1;\n}\n',
                      "<?php\nfunction f($x){$s='hello';return $x + 1;}\n"):
            m = self.measurement(before, after)
            for key in ('net_units', 'churn', 'structural_churn', 'files_changed', 'ast_delta', 'complexity_delta'):
                self.assertEqual(m[key], 0, (key, after))

    def test_variable_is_one_unit_and_rename_is_churn(self):
        before, after = '<?php $x = 1;\n', '<?php $longer = 1;\n'
        self.assertEqual(self.labels(before), ['assignment_expression[=]', 'variable_name:$x', 'integer:1'])
        m = self.measurement(before, after)
        self.assertEqual((m['units_added'], m['units_deleted'], m['net_units'], m['churn']), (1, 1, 0, 2))
        self.assertEqual(m['structural_churn'], 0)

    def test_new_method_adds_units_and_complexity(self):
        before = '<?php\nclass Calc {}\n'
        after = '<?php\nclass Calc {\n    public function total($items) { return array_sum($items); }\n}\n'
        m = self.measurement(before, after)
        self.assertGreater(m['net_units'], 0)
        self.assertEqual(m['complexity_delta'], 1)
        self.assertIn('method_declaration[public,function]', self.labels(after))
        self.assertEqual(self.labels(after).count('EndBlock'), 2)

    def test_branch_and_function_types(self):
        for code, expected in (
            ('if ($x) {} elseif ($y) {} else if ($z) {} else {}', 3),
            ('switch ($x) { case 1: break; default: break; }', 2),
            ('$a = match ($x) { 1, 2 => 3, default => 4 };', 2),
            ('for ($i=0; $i<5; $i++) {} foreach ($xs as $x) {} while ($x) {} do {} while ($x);', 4),
            ('try {} catch (Exception $e) {}', 1),
            ('$a = $x ? $y : $z; $b = $x ?? $y ?? $z;', 3),
            ('$x ??= $y;', 1),
            ('function f() {} $f = function() {}; $g = fn($x) => $x;', 3),
            ('$a = $x && $y || $z; $b = $x and $y or $z;', 4),
            ('if ($x): echo 1; elseif ($y): echo 2; else: echo 3; endif;', 2),
        ):
            with self.subTest(code=code):
                self.assertEqual(structure(parse('<?php ' + code, 'x.php'))[1], expected)

    def test_operators_and_modifiers_fold_into_parent(self):
        for before, after in (('$x = $a + $b;', '$x = $a - $b;'),
                              ('$x = $a . $b;', '$x = $a + $b;'),
                              ('class A { public function f() {} }', 'class A { private function f() {} }')):
            m = self.measurement('<?php ' + before + '\n', '<?php ' + after + '\n')
            self.assertEqual((m['net_units'], m['churn']), (0, 2))

    def test_test_vendor_and_generated_files_excluded(self):
        for path in ('tests/Calc.php', 'src/CalcTest.php', 'vendor/lib/Calc.php'):
            m = self.measurement('<?php $x = 1;\n', '<?php $x = 2;\n', path)
            self.assertEqual(m['excluded_files'], [path])
            self.assertEqual(m['net_units'], 0)
        before = '<?php\n// @generated\n$x = 1;\n'
        self.assertEqual(self.measurement(before, before.replace('1', '2'))['excluded_files'], ['src/calc.php'])
        m = self.measurement('<?php $x = 1;\n', '<?php // @generated\n$x = 2;\n')
        self.assertGreater(m['churn'], 0)

    def test_inline_html_and_tags_not_counted(self):
        before = '<h1>Hello</h1>\n<?php $x = 1; ?>\n<p>Before</p>\n'
        after = '<h2>Different</h2>\n<?php $x = 1; ?>\n<p>After</p>\n'
        m = self.measurement(before, after, 'templates/page.phtml')
        for key in ('net_units', 'churn', 'token_churn', 'files_changed', 'ast_delta', 'complexity_delta'):
            self.assertEqual(m[key], 0, key)
        self.assertEqual(self.labels(before), self.labels('<?php $x = 1;'))
        self.assertEqual(self.labels('<h1>HTML only</h1>'), [])
        self.assertEqual(token_lines(parse('<h1>HTML only</h1>', 'x.php')), [])
        self.assertEqual(structure(parse(before, 'x.php')), structure(parse('<?php $x = 1;', 'x.php')))
        m = self.measurement('<?php $x = 1;\n', '<?php $x = 1; ?>\n')
        self.assertEqual((m['churn'], m['token_churn'], m['ast_delta']), (0, 0, 0))

    def test_added_root_file_empty_large_tree_and_eof(self):
        m = self.measurement('', '<?php function f() {}\n', 'index.php')
        self.assertGreater(m['net_units'], 0)
        self.assertEqual(m['excluded_files'], [])
        self.assertEqual(unit_lines(parse('', 'x.php')), [])
        source = '<?php\n' + '$value = 1;\n' * 2000
        parsed = parse(source, 'x.php')
        self.assertEqual(len(token_lines(parsed)), 2000)
        self.assertEqual(len(unit_lines(parsed)), 2000)
        for source in (b'', b'<?php $x = 1;', b'<?php $x = 1;\n'):
            self.assertEqual(parse(source, 'x.php').source, source)
        self.assertEqual(token_diff(unit_lines(parse('<?php $x = 1;', 'x.php')),
                                    unit_lines(parse('<?php $x = 1;\n', 'x.php'))), (0, 0, False))

    def test_invalid_syntax_and_patch_only_rejected(self):
        for source in ('<?php function {', '<?php $x = ;', '<?php function f() {', '<?php $x = "unterminated'):
            with self.subTest(source=source), self.assertRaisesRegex(ValueError, 'invalid or recovered php syntax'):
                parse(source, 'x.php')
        with self.assertRaisesRegex(ValueError, 'full-file'):
            measure(diff('<?php $x = 1;\n', '<?php $x = 2;\n'), language='php')


if __name__ == '__main__':
    unittest.main()
