import difflib
import importlib.util
import unittest
from importlib import metadata
from unittest.mock import patch

from parsimony import languages
from parsimony.analysis import generated, implementation, measure, parse_patch, token_diff
from parsimony.languages import extension_language, parse, structure, token_lines, track, unit_lines


HAS_RUST = all(importlib.util.find_spec(name) for name in ('tree_sitter', 'tree_sitter_rust'))


def diff(before, after, path='src/calc.rs'):
    return ''.join(difflib.unified_diff(before.splitlines(keepends=True), after.splitlines(keepends=True),
                                       fromfile='a/' + path if before else '/dev/null',
                                       tofile='b/' + path if after else '/dev/null'))


class RustScopeTests(unittest.TestCase):
    def test_extensions_and_scope(self):
        self.assertIn('rust', languages.SUPPORTED)
        for path in ('lib.rs', 'main.rs', 'build.rs', 'src/lib.rs', 'crates/a/build.rs',
                     'crates/a/src/CALC.RS', 'src/testing/helpers.rs', 'src/contest.rs'):
            self.assertEqual(extension_language(path), 'rust')
            self.assertTrue(implementation(path, 'rust'), path)
            self.assertFalse(implementation(path), path)
        for path in ('src/calc.rlib', 'src/calc.ron', 'Cargo.toml'):
            self.assertIsNone(extension_language(path))
        for path in ('tests/calc.rs', 'crates/a/tests/calc.rs', 'crates/a/src/tests/calc.rs',
                     'benches/calc.rs', 'crates/a/benches/calc.rs', 'crates/a/src/benches/calc.rs',
                     'examples/main.rs', 'crates/a/examples/main.rs', 'crates/a/src/examples/main.rs',
                     'tests.rs', 'src/tests.rs', 'crates/a/src/calc_test.rs', 'src/test_calc.rs',
                     'target/debug/build/lib.rs', 'crates/a/target/lib.rs', 'src/target/lib.rs',
                     'vendor/lib.rs', 'vendored/lib.rs', 'third_party/lib.rs', 'docs/lib.rs',
                     'generated/lib.rs', 'src/calc.generated.rs', 'build/lib.rs', 'src/calc.ron'):
            self.assertFalse(implementation(path, 'rust'), path)

    def test_generated_headers(self):
        for header in ('// Code generated by tool. DO NOT EDIT.', '/* Auto-generated file */',
                       '/**\n * @generated\n */', '// This file is generated by tool'):
            self.assertTrue(generated(header + '\nfn f() {}\n', 'rust'), header)
        self.assertFalse(generated('fn f() { let s = "generated by a user"; }\n', 'rust'))

    def test_metadata_pin_and_install_guidance(self):
        with patch.object(languages.metadata, 'version', side_effect=languages._RUST_PINS.get), \
                patch.object(languages.metadata, 'distribution') as distribution:
            self.assertEqual(track('rust'), {'language': 'rust', 'unit_version': 'tree-sitter-rust-units-v1',
                                            'versions': {'tree-sitter': '0.26.0', 'tree-sitter-rust': '0.24.0'}})
            distribution.assert_not_called()
        with patch.object(languages.metadata, 'version', side_effect=metadata.PackageNotFoundError('tree-sitter-rust')):
            with self.assertRaisesRegex(ValueError, 'pip install.*tree-sitter-rust==0.24.0'):
                track('rust')
        for name in languages._RUST_PINS:
            versions = {**languages._RUST_PINS, name: '0.0.0'}
            with patch.object(languages.metadata, 'version', side_effect=versions.get):
                with self.assertRaisesRegex(ValueError, 'requires exact versions'):
                    track('rust')
                with self.assertRaisesRegex(ValueError, 'requires exact versions'):
                    parse('fn f() {}', 'x.rs')

    def test_metadata_only_diff_rejected(self):
        with self.assertRaisesRegex(ValueError, 'mode-only diff unsupported'):
            parse_patch('diff --git a/src/a.rs b/src/a.rs\nold mode 100644\nnew mode 100755\n', 'rust')

    def test_existing_language_scope_unchanged(self):
        for language, suffix in (('go', 'go'), ('php', 'php'), ('javascript', 'js'), ('typescript', 'ts')):
            for path in (f'benches/lib.{suffix}', f'target/lib.{suffix}', f'src/tests.{suffix}'):
                self.assertTrue(implementation(path, language), (language, path))


@unittest.skipUnless(HAS_RUST, 'install parsimony-benchmark[languages] for Rust grammar tests')
class RustMeasurementTests(unittest.TestCase):
    def measurement(self, before, after, path='src/calc.rs'):
        return measure(diff(before, after, path), lambda _: before, language='rust')

    def labels(self, source, keep_values=True):
        return [label for row in unit_lines(parse(source, 'x.rs'), keep_values) for label in row]

    def assert_no_change(self, before, after):
        m = self.measurement(before, after)
        for key in ('net_units', 'churn', 'structural_churn', 'token_churn', 'files_changed',
                    'ast_delta', 'complexity_delta'):
            self.assertEqual(m[key], 0, (key, after))

    def test_worked_example(self):
        before = ('fn total(items: &[i32]) -> i32 {\n    let mut result = 0;\n'
                  '    for item in items { result = result + item; }\n    result\n}\n')
        after = 'fn total(items: &[i32]) -> i32 { items.iter().sum() }\n'
        m = self.measurement(before, after)
        self.assertLess(m['net_units'], 0)
        self.assertGreater(m['units_deleted'], m['units_added'])
        self.assertEqual(m['complexity_delta'], -1)
        self.assertEqual(m['measurement_track'], track('rust'))

    def test_comments_whitespace_and_formatting(self):
        before = 'fn f(x:i32)->i32{let s="hello";x+1}\n'
        for after in ('// note\n/* nested /* comment */ note */\n/// doc\n' + before,
                      '\nfn f(x: i32) -> i32 {\n    let s = "hello";\n    x + 1\n}\n'):
            self.assert_no_change(before, after)
        self.assert_no_change('fn f(){foo!(a + 1);}\n',
                              'fn f() {\n    foo! (a /* note */ +\n        1);\n}\n')
        self.assertEqual(self.measurement(before, before.replace('x+1', '(x+1)'))['churn'], 0)

    def test_named_nodes_and_rename(self):
        before = 'fn f() { let x = 1; }\n'
        self.assertEqual(self.labels(before), ['function_item[fn]', 'identifier:f', 'block',
                                              'let_declaration[let,=]', 'identifier:x',
                                              'integer_literal:1', 'EndBlock'])
        m = self.measurement(before, before.replace('let x', 'let longer'))
        self.assertEqual((m['units_added'], m['units_deleted'], m['net_units'], m['churn']), (1, 1, 0, 2))
        self.assertEqual(m['structural_churn'], 0)

    def test_operators_and_modifiers_fold_into_parent(self):
        for before, after in (('fn f(){let x=a+b;}\n', 'fn f(){let x=a-b;}\n'),
                              ('fn f(){let x=1;}\n', 'fn f(){let mut x=1;}\n'),
                              ('fn f(){}\n', 'pub fn f(){}\n'),
                              ('fn f(){}\n', 'async fn f(){}\n')):
            m = self.measurement(before, after)
            self.assertEqual((m['net_units'], m['churn']), (0, 2), (before, after))

    def test_struct_enum_trait_impl_generics_and_closures(self):
        source = ('pub struct Calc<T> { value: T }\n'
                  'enum State { Ready, Value(i32) }\n'
                  'trait Total { fn total(&self) -> i32; }\n'
                  'impl Total for Calc<i32> { fn total(&self) -> i32 { self.value } }\n'
                  'fn twice<T>(x: T) -> T { let f = |v| v; f(x) }\n')
        m = self.measurement('', source, 'lib.rs')
        self.assertGreater(m['net_units'], 0)
        self.assertEqual(m['complexity_delta'], 4)
        self.assertGreaterEqual(self.labels(source).count('EndBlock'), 5)

    def test_branch_and_function_types(self):
        for code, expected in (
            ('fn f(){if x {} else if y {} else {}}', 3),
            ('fn f(){match x { 1 | 2 => a(), _ => b() }}', 3),
            ('fn f(){for x in xs {} while x {} loop {break;}}', 4),
            ('fn f(){let a = x && y || z;}', 3),
            ('fn f(){let a = g()?;}', 2),
            ('fn f(){let g = |x| x;}', 2),
            ('fn f(){foo!(if x { loop {} });}', 1),
        ):
            with self.subTest(code=code):
                self.assertEqual(structure(parse(code, 'x.rs'))[1], expected)

    def test_macro_invocation_tokens_and_edits(self):
        before = 'fn f(){foo!(x + 1);}\n'
        labels = self.labels(before)
        self.assertIn('macro_invocation[!]', labels)
        self.assertIn('identifier:foo', labels)
        self.assertIn('identifier:x', labels)
        self.assertIn('token:+', labels)
        self.assertIn('token:(', labels)
        self.assertIn('token:)', labels)
        self.assertNotIn('token_tree', labels)
        self.assertFalse(any(label.startswith('call_expression') for label in labels))
        for after in ('fn f(){foo!(x - 1);}\n', 'fn f(){foo!(x + 2);}\n',
                      'fn f(){bar!(x + 1);}\n'):
            m = self.measurement(before, after)
            self.assertEqual((m['net_units'], m['churn']), (0, 2))
            self.assertGreater(m['token_churn'], 0)
        self.assertGreater(self.measurement(before, 'fn f(){foo!(x + 1, y);}\n')['net_units'], 0)
        source = ('macro_rules! identity { ($x:expr) => { $x }; }\n'
                  'fn f() { identity!(not valid Rust expressions @@@); }\n')
        self.assertGreater(len(self.labels(source)), 0)
        self.assertEqual(structure(parse(source, 'x.rs'))[1], 1)

    def test_literals_are_value_sensitive_atoms(self):
        for literal in ('"hello\\nworld"', 'r###"hello"###', 'b"hello"', "'a'", "b'a'", '1u64', '1.5f32', 'true'):
            with self.subTest(literal=literal):
                labels = self.labels(f'fn f(){{let x={literal};}}')
                self.assertEqual(len(labels), 7)
                self.assertTrue(any(label.endswith(':' + literal) for label in labels), labels)
        m = self.measurement('fn f(){let x="a";}\n', 'fn f(){let x="b";}\n')
        self.assertEqual((m['net_units'], m['churn'], m['structural_churn']), (0, 2, 0))

    def test_path_exclusions_are_checked_before_reading_or_parsing(self):
        for path in ('tests/bad.rs', 'crates/a/tests/bad.rs', 'crates/a/benches/bad.rs',
                     'crates/a/examples/bad.rs', 'src/tests.rs', 'src/calc_test.rs', 'target/bad.rs',
                     'vendor/bad.rs', 'src/bad.generated.rs'):
            with self.subTest(path=path):
                with patch('parsimony.languages.parse', side_effect=AssertionError('must not parse')):
                    m = measure(diff('invalid source\n', 'also invalid\n', path),
                                lambda _: self.fail('must not read'), language='rust')
                self.assertEqual(m['excluded_files'], [path])
                self.assertEqual((m['net_units'], m['churn'], m['files_changed']), (0, 0, 0))

    def test_generated_exclusion_uses_only_base(self):
        before = '// @generated\nfn f(){let x=1;}\n'
        self.assertEqual(self.measurement(before, before.replace('1', '2'))['excluded_files'], ['src/calc.rs'])
        m = self.measurement('fn f(){let x=1;}\n', '// @generated\nfn f(){let x=2;}\n')
        self.assertEqual(m['churn'], 2)
        self.assertGreater(self.measurement('', before)['net_units'], 0)

    def test_direct_cfg_test_modules_excluded(self):
        implementation_source = 'fn f() {}\n'
        for attributes in ('#[cfg(test)]', '#[cfg ( /* note */ test )]',
                           '#[allow(dead_code)]\n#[cfg(test)]', '#[cfg(test)]\n#[allow(dead_code)]'):
            with self.subTest(attributes=attributes):
                before = implementation_source + attributes + '\n// between\npub mod t { fn t(){foo!(1);} }\n'
                after = before.replace('foo!(1)', 'if true { foo!(1, 2); }')
                self.assert_no_change(before, after)
                self.assert_no_change(implementation_source, before)
                self.assertEqual(self.labels(before), self.labels(implementation_source))
        self.assert_no_change('mod outer { fn f() {} }\n',
                              'mod outer { fn f() {} #[cfg(test)] mod t { fn t() {} } }\n')

    def test_cfg_filter_does_not_hide_implementation(self):
        for source in ('#[cfg(not(test))] mod t { fn f(){let x=1;} }\n',
                       '#[cfg(any(test, feature="x"))] mod t { fn f(){let x=1;} }\n',
                       '#[cfg(test)] fn f(){let x=1;}\n',
                       '#[cfg(test)] use x::y; mod t { fn f(){let x=1;} }\n',
                       '#[cfg(test)] mod t {} fn f(){let x=1;}\n',
                       '#[doc = "#[cfg(test)]"] mod t { fn f(){let x=1;} }\n',
                       'fn f(){let x=1;} mod tests { fn t(){} }\n'):
            with self.subTest(source=source):
                self.assertEqual(self.measurement(source, source.replace('1', '2'))['churn'], 2)

    def test_deletion_is_negative_and_build_script_counts(self):
        before = 'fn main(){println!("hello");}\n'
        m = self.measurement(before, '', 'build.rs')
        self.assertEqual(m['units_added'], 0)
        self.assertEqual(m['net_units'], -sum(map(len, unit_lines(parse(before, 'build.rs')))))
        self.assertGreater(m['units_deleted'], 0)
        self.assertEqual(m['complexity_delta'], -1)
        self.assertEqual(m['excluded_files'], [])
        self.assertGreater(self.measurement('', before, 'build.rs')['net_units'], 0)

    def test_empty_large_tree_and_eof(self):
        self.assertEqual(unit_lines(parse('', 'x.rs')), [])
        self.assertEqual(token_lines(parse('', 'x.rs')), [])
        source = 'fn f(){\n' + 'let value = 1;\n' * 2000 + '}\n'
        parsed = parse(source, 'x.rs')
        self.assertEqual(len(unit_lines(parsed)), 2002)
        self.assertEqual(len(token_lines(parsed)), 2001)
        for source in (b'', b'fn f(){}', b'fn f(){}\n'):
            self.assertEqual(parse(source, 'x.rs').source, source)
        self.assertEqual(token_diff(unit_lines(parse('fn f(){}', 'x.rs')),
                                    unit_lines(parse('fn f(){}\n', 'x.rs'))), (0, 0, False))

    def test_invalid_syntax_and_patch_only_rejected(self):
        for source in ('fn {', 'fn f(){let x=;}', 'fn f(){', 'fn f(){let s="unterminated;}',
                       '#[cfg(test)] mod t { fn { }'):
            with self.subTest(source=source), self.assertRaisesRegex(ValueError, 'invalid or recovered rust syntax'):
                parse(source, 'x.rs')
        with self.assertRaisesRegex(ValueError, 'full-file'):
            measure(diff('fn f(){}\n', 'fn g(){}\n'), language='rust')


